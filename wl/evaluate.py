"""Offline evaluation on reserves the demo never uses. Writes docs/evaluation.md.

    python -m wl.evaluate
"""
import pathlib

import numpy as np

from . import engine, seed, world

SEEDS = range(300, 312)


def analyse(w, model, thr):
    """Everything the API derives from a month of data, as plain values. Shared with the tests."""
    n = w["n_cameras"]
    cams = [s["xy"] for s in w["sensors"][:n]]
    snd = [o for o in w["observations"] if o["kind"] == "sound"]
    proba = model.predict_proba(np.array([o["features"] for o in snd]))
    gi, ei = list(model.classes_).index("gunshot"), list(model.classes_).index("engine")
    heard = [(w["sensors"][o["sensor"]]["xy"], engine.night_of(o["day"], o["hour"]), "gunshot" if p[gi] >= thr else "engine", o["truth"]["sound"])
             for o, p in zip(snd, proba) if p[gi] >= thr or (p[ei] >= 0.9 and engine.is_night(o["hour"]))]
    veh = [(o["sensor"], o["day"], o["hour"], o["confidence"]) for o in w["observations"] if o["kind"] == "vehicle"]
    clusters, counts = engine.vehicle_clusters(veh, cams, [h[:3] for h in heard])
    return cams, snd, proba, heard, clusters, counts


def main():
    model, thr, sm = seed.train()
    occ = {"all": [], "confident": [], "model": []}
    hard = {"confident": [], "model": []}
    shifts, pvals, null_p = [], [], []
    found = false_clusters = raw_night = g_true = g_alert = g_hit = rule_alert = rule_hit = 0
    cover, base_cover = [], []
    for s in SEEDS:
        w = world.build(s)
        n = w["n_cameras"]
        cams, snd, proba, heard, clusters, counts = analyse(w, model, thr)
        for sp, (_, _, p, _) in world.SPECIES.items():
            for per, days in enumerate((range(0, world.LOSS_DAY), range(world.LOSS_DAY, world.DAYS))):
                true = len(w["occupied"][sp, per]) / n
                dets = [(o["sensor"], o["day"], o["confidence"]) for o in w["observations"] if o["kind"] == "animal" and o["label"] == sp]
                y_all = engine.histories([(a, d) for a, d, _ in dets], n, days)
                y = engine.histories([(a, d) for a, d, c in dets if c >= engine.SITE_CONFIDENCE], n, days)
                est = engine.occupancy(y, boot=0)
                occ["all"].append(abs((y_all.sum(1) > 0).mean() - true))
                occ["confident"].append(abs(est["naive"] - true))
                occ["model"].append(abs(est["psi"] - true))
                if p <= 0.2:
                    hard["confident"].append(est["naive"] - true)
                    hard["model"].append(est["psi"] - true)
        el = [(cams[o["sensor"]][0], o["day"]) for o in w["observations"] if o["kind"] == "animal" and o["label"] == "elephant" and o["confidence"] >= engine.MIN_CONFIDENCE]
        sh = engine.shift([x for x, d in el if d < world.LOSS_DAY], [x for x, d in el if d >= world.LOSS_DAY], perms=1000, seed=s)
        shifts.append(sh["shift_km"])
        pvals.append(sh["p_value"])
        zb = [(cams[o["sensor"]][0], o["day"]) for o in w["observations"] if o["kind"] == "animal" and o["label"] == "antelope" and o["confidence"] >= engine.MIN_CONFIDENCE]
        null_p.append(engine.shift([x for x, d in zb if d < world.LOSS_DAY], [x for x, d in zb if d >= world.LOSS_DAY], perms=1000, seed=s)["p_value"])
        hot = [c for c in clusters if np.hypot(c["centre"][0] - world.HOTSPOT[0], c["centre"][1] - world.HOTSPOT[1]) < 3]
        found += bool(hot)
        false_clusters += len(clusters) - len(hot)
        raw_night += counts["cameras_with_any"]
        g_true += sum(o["truth"]["sound"] == "gunshot" for o in snd)
        g_alert += sum(h[2] == "gunshot" for h in heard)
        g_hit += sum(h[2] == "gunshot" and h[3] == "gunshot" for h in heard)
        rule = [o for o in snd if engine.loud_and_short(o["features"])]
        rule_alert += len(rule)
        rule_hit += sum(o["truth"]["sound"] == "gunshot" for o in rule)
        risk = engine.risk_tiles(clusters, [h[0] for h in heard if h[2] == "gunshot"], [t["xy"] for t in w["tracks"] if t["day"] >= world.LOSS_DAY][::8])
        cover.append(engine.covered(risk, engine.patrols(risk, ms=400)))
        base_cover.append(engine.covered(risk, engine.perimeter()))
    k = len(SEEDS)
    m = lambda xs: float(np.mean(xs))      # noqa: E731
    lines = ["# Evaluation", "",
             f"Generated by `python -m wl.evaluate` on {k} synthetic reserves (seeds {SEEDS[0]} to {SEEDS[-1]}; 60 cameras, 16 microphones, 30 days each) that the demo and the tests never use.",
             "There are no photographs or recordings: a camera detection is a label with a confidence, a sound is five summary features. Read these as a check that the methods work, not as field accuracy.", "",
             "## 1. Which sites does each species use?", "",
             f"Six species, two 15-day periods, {k} reserves. Error is the absolute difference from the true share of camera sites used.", "",
             "| | Mean absolute error |", "|---|---|", f"| Any detection of the species at the site, at any confidence | {m(occ['all']):.3f} |",
             f"| Any detection at confidence {engine.SITE_CONFIDENCE} or more | {m(occ['confident']):.3f} |", f"| Occupancy model on those confident detections | {m(occ['model']):.3f} |", "",
             f"For the two hard-to-see species (leopard, hyena; detected on at most a fifth of days where present) the confident count is off by {m(hard['confident']):+.3f} on average and the occupancy model by {m(hard['model']):+.3f}.",
             "Counting every low-confidence label puts almost every species almost everywhere: the confidence threshold is what matters most. For shy species the confident count misses sites where the animal was never caught;",
             "the occupancy model corrects in the right direction and overshoots by about as much, because one confident mislabel at an unused site counts as presence. On average it is no better than the plain count here.", "",
             "## 2. Corridor shift", "",
             f"The herd's crossing point moves {world.CORRIDOR[1] - world.CORRIDOR[0]:.1f} km east on day {world.LOSS_DAY}. Estimated from confident camera detections alone: {m(shifts):.2f} km on average (range {min(shifts):.2f} to {max(shifts):.2f}); permutation p below 0.01 in {sum(p < 0.01 for p in pvals)} of {k} reserves.",
             f"The same test on antelope, which do not migrate, gave p below 0.01 in {sum(p < 0.01 for p in null_p)} of {k}. Antelope do lose sites in the cleared block, so some real movement is expected there.", "",
             "## 3. Night vehicles", "",
             f"Each reserve has one planted pattern: vehicles on six nights at three cameras on the boundary track. Found in {found} of {k} reserves, with {false_clusters} other clusters raised.",
             f"For scale: {raw_night / k:.0f} cameras per reserve recorded at least one night-time \"vehicle\" label at some confidence; alerting on each would be {raw_night / k:.0f} sites to visit instead of one.", "",
             "## 4. Gunshots", "",
             f"Sound classifier: {sm['accuracy']:.1%} accuracy over five classes on {sm['n_test']:,} held-out sounds. On that balanced test set a 0.5 threshold looks excellent ({sm['at_0.5']['precision_on_balanced_test']:.1%} precision),",
             f"but a gunshot is about one sound in a thousand in the field, where the same threshold would be right {sm['at_0.5']['precision_expected_in_field']:.1%} of the time. The alert threshold ({thr}) is the lowest at which a quarter of alerts are expected to be real at that prevalence; it keeps {sm['chosen']['recall']:.1%} of gunshots.", "",
             "| Across the reserves | Alerts raised | True gunshots among them | True gunshots in the data |", "|---|---|---|---|",
             f"| Classifier at the chosen threshold | {g_alert} | {g_hit} | {g_true} |", f"| Baseline: short and loud | {rule_alert} | {rule_hit} | {g_true} |", "",
             f"Gunshots are {g_true} of about {k * 2700:,} sounds. The strict threshold trades missed gunshots for alerts a ranger can afford to act on, and an alert is still evidence for a person to weigh, cross-checked against cameras.", "",
             "## 5. Patrols", "",
             "Share of mapped risk within 1.5 km of a patrol path, three teams, eight hours each:", "",
             "| | Risk covered |", "|---|---|", f"| Prize-collecting routes | {m(cover):.1%} |", f"| Baseline: each team follows a stretch of the boundary track | {m(base_cover):.1%} |", "",
             "The risk map is built from the same alerts the routes are then scored on, and its weights are a judgement, so this measures the router, not whether patrols prevent poaching."]
    out = pathlib.Path(__file__).resolve().parent.parent / "docs" / "evaluation.md"
    out.write_text("\n".join(lines) + "\n")
    print(out.read_text())


if __name__ == "__main__":
    main()
